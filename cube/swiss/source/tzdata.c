const char *get_timezone(const char *name)
{
	const char *start = name;
	const char *end = strchr(start, '/');
	struct TZData *tzdata = &TZData;

find:
	if (end) {
		for (int i = 0; i < tzdata->count; i++) {
			if (!strncmp(tzdata->timezones[i].name, start, end - start + 1)) {
				tzdata = &tzdata->timezones[i];
				start = end + 1;
				end = strchr(start, '/');
				goto find;
			}
		}
	} else {
		for (int i = 0; i < tzdata->count; i++) {
			if (!strcmp(tzdata->timezones[i].name, start)) {
				tzdata = &tzdata->timezones[i];
				return tzdata->timezone;
			}
		}
	}

	return NULL;
}
